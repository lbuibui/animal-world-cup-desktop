// Sync / generate app/data/fixtures.json — the group-stage schedule shown on
// the Landing page (昨日 / 今日 / 明日 rounds) and its future rounds.
//
//   node script/sync-fixtures.mjs               # validate + extend + write back
//   node script/sync-fixtures.mjs --check       # validate only (exit 1 on error)
//   node script/sync-fixtures.mjs --reset       # rebuild a clean round-robin, no history
//   node script/sync-fixtures.mjs --rounds 10   # target total round count
//   node script/sync-fixtures.mjs --current-round 2   # which round is "today"
//
// Schedule math: 8 playable teams → C(8,2) = 28 pairings. A circle-method
// round robin packs them into 7 rounds of 4 matches (every team plays every
// round; home/away alternates per round so no team is always at home).
//
// Default "extend" mode keeps every existing match verbatim — finished scores
// and already-announced kick-offs are history and must not be rewritten — and
// appends new rounds built from pairings that do not appear anywhere in the
// current file, until the round-robin is complete.
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { PLAYABLE_TEAMS } from "../app/data/teams.js";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const FIXTURES_PATH = path.resolve(__dirname, "..", "app", "data", "fixtures.json");

const TEAM_IDS = PLAYABLE_TEAMS.map((t) => t.id);
const TEAM_SET = new Set(TEAM_IDS);
// Non-playable teams allowed to appear in "locked" (upcoming) placeholder
// slots. Unknown ids elsewhere are a warning, not an error — the schedule is
// free to tease teams that do not exist in app/data/teams.js yet.
const UPCOMING_TEAM_SET = new Set(["japan", "korea", "italy", "netherlands"]);

const STATUSES = ["finished", "scheduled", "locked"];
const VENUES = ["Daisy Park", "Acorn Arena"];
// Kick-off template for the 4 matches of a round, in order.
const SLOT_TEMPLATE = [
  ["19:00", VENUES[0]],
  ["21:00", VENUES[1]],
  ["21:30", VENUES[0]],
  ["22:00", VENUES[1]],
];
const DAY_LABELS = ["昨日", "今日", "明日", "后天"];
const roundLabel = (n) =>
  `小组赛 · 第 ${n} 轮 · ${DAY_LABELS[n] ?? "未来"}`;
const SOURCE_LINE =
  "generated by script/sync-fixtures.mjs — 8-team round robin (circle method); see script/sync-fixtures.mjs --help";

// ---- schedule math ----------------------------------------------------------

// Circle method (Berger tables) for an even-sized team list. Team 0 stays
// fixed, the rest rotate one step per round. Returns rounds of [home, away]
// pairs; the home/away bias flips every round so the fixed team and everyone
// else split home/away games evenly.
function roundRobinRounds(teamIds) {
  const fixed = teamIds[0];
  let rest = teamIds.slice(1);
  const rounds = [];
  for (let round = 0; round < teamIds.length - 1; round++) {
    const lineup = [fixed, ...rest];
    const pairs = [];
    for (let i = 0; i < lineup.length / 2; i++) {
      const a = lineup[i];
      const b = lineup[lineup.length - 1 - i];
      const home = round % 2 === 0 ? a : b;
      pairs.push([home, home === a ? b : a]);
    }
    rounds.push(pairs);
    rest = [...rest.slice(1), rest[0]];
  }
  return rounds;
}

// "england-france" / "france-england" are the same pairing for dedup purposes.
function pairKey(home, away) {
  return [home, away].sort().join("-");
}

// Pairings already committed in the file (finished/scheduled; locked slots
// don't occupy a pairing).
function countUsedPairings(base) {
  const used = new Set();
  for (const round of base?.rounds ?? []) {
    for (const m of round.matches) {
      if (m.status !== "locked") used.add(pairKey(m.home, m.away));
    }
  }
  return used;
}

function buildMatch(n, home, away, idx) {
  const [time, venue] = SLOT_TEMPLATE[idx % SLOT_TEMPLATE.length];
  return {
    id: `r${n}-${home}-${away}`,
    home,
    away,
    when: `${time} · ${venue}`,
    status: "scheduled",
  };
}

function buildResetRounds() {
  return roundRobinRounds(TEAM_IDS).map((pairs, n) => ({
    id: `r${n}`,
    label: roundLabel(n),
    matches: pairs.map(([home, away], idx) => buildMatch(n, home, away, idx)),
  }));
}

// Extend `existing` (may be null for a fresh file) up to `targetRounds`.
// Pairings already used anywhere in the file are skipped; the remaining
// round-robin pairings are packed into new rounds with a greedy matching:
// each round takes up to 4 pairings where no team appears twice — a team
// plays exactly once per round in a round robin, and a naive slice after
// removing used pairings would put e.g. usa in two r3 matches.
function buildExtendedRounds(existing, targetRounds) {
  const used = new Set();
  for (const round of existing?.rounds ?? []) {
    for (const m of round.matches) {
      if (m.status !== "locked") used.add(pairKey(m.home, m.away));
    }
  }
  const fresh = [];
  for (const pairs of roundRobinRounds(TEAM_IDS)) {
    for (const [home, away] of pairs) {
      if (used.has(pairKey(home, away))) continue;
      used.add(pairKey(home, away));
      fresh.push([home, away]);
    }
  }
  const newRounds = [];
  let n = existing?.rounds?.length ?? 0;
  while (fresh.length && n < targetRounds) {
    const taken = [];
    const busy = new Set();
    for (let i = 0; i < fresh.length && taken.length < 4; ) {
      const [home, away] = fresh[i];
      if (busy.has(home) || busy.has(away)) {
        i++;
        continue;
      }
      busy.add(home);
      busy.add(away);
      taken.push(fresh.splice(i, 1)[0]); // splice shifts — don't advance i
    }
    newRounds.push({
      id: `r${n}`,
      label: roundLabel(n),
      matches: taken.map(([home, away], idx) => buildMatch(n, home, away, idx)),
    });
    n++;
  }
  return newRounds;
}

// ---- validation -------------------------------------------------------------

function validateFixtures(data) {
  const errors = [];
  const warnings = [];
  if (!data || typeof data !== "object" || Array.isArray(data)) {
    return { errors: ["fixtures root must be an object"], warnings };
  }
  if (!Array.isArray(data.rounds) || data.rounds.length === 0) {
    errors.push("rounds must be a non-empty array");
    return { errors, warnings };
  }
  if (!Number.isInteger(data.currentRound) || data.currentRound < 0 || data.currentRound >= data.rounds.length) {
    errors.push(`currentRound must be an integer in [0, ${data.rounds.length - 1}] (got ${data.currentRound})`);
  }
  if (typeof data.updatedAt !== "string" || !/^\d{4}-\d{2}-\d{2}$/.test(data.updatedAt)) {
    warnings.push(`updatedAt should be an ISO date string (got ${JSON.stringify(data.updatedAt)})`);
  }

  const seenIds = new Set();
  const seenPairings = new Set();
  data.rounds.forEach((round, i) => {
    if (round.id !== `r${i}`) {
      errors.push(`rounds[${i}].id must be "r${i}" (got ${JSON.stringify(round.id)})`);
    }
    if (typeof round.label !== "string" || !round.label) {
      errors.push(`rounds[${i}].label must be a non-empty string`);
    }
    if (!Array.isArray(round.matches) || round.matches.length === 0) {
      errors.push(`rounds[${i}].matches must be a non-empty array`);
      return;
    }
    round.matches.forEach((m, j) => {
      const where = `rounds[${i}].matches[${j}]`;
      if (seenIds.has(m.id)) errors.push(`${where}: duplicate id ${JSON.stringify(m.id)}`);
      seenIds.add(m.id);
      if (!/^r\d+-[a-z]+-[a-z]+$/.test(m.id ?? "")) {
        errors.push(`${where}: id must match r<round>-<home>-<away> (got ${JSON.stringify(m.id)})`);
      }
      if (!STATUSES.includes(m.status)) {
        errors.push(`${where}: status must be one of ${STATUSES.join("/")} (got ${JSON.stringify(m.status)})`);
        return;
      }
      if (m.status === "finished") {
        if (!TEAM_SET.has(m.home) || !TEAM_SET.has(m.away)) {
          errors.push(`${where}: finished match must use playable teams (${JSON.stringify([m.home, m.away])})`);
        }
        if (m.when !== "FT") errors.push(`${where}: finished match when must be "FT" (got ${JSON.stringify(m.when)})`);
        if (
          !Array.isArray(m.score) ||
          m.score.length !== 2 ||
          !Number.isInteger(m.score[0]) ||
          !Number.isInteger(m.score[1]) ||
          m.score[0] < 0 ||
          m.score[1] < 0
        ) {
          errors.push(`${where}: finished match needs score [home, away] of non-negative integers (got ${JSON.stringify(m.score)})`);
        }
        const key = pairKey(m.home, m.away);
        if (seenPairings.has(key)) errors.push(`${where}: duplicate pairing ${key} in this file`);
        seenPairings.add(key);
      } else if (m.status === "scheduled") {
        if (!TEAM_SET.has(m.home) || !TEAM_SET.has(m.away)) {
          errors.push(`${where}: scheduled match must use playable teams (${JSON.stringify([m.home, m.away])})`);
        }
        if (typeof m.when !== "string" || !/^\d{2}:\d{2} · /.test(m.when)) {
          errors.push(`${where}: scheduled match when must be "HH:MM · Venue" (got ${JSON.stringify(m.when)})`);
        }
        if (m.score !== undefined) errors.push(`${where}: scheduled match must not carry a score`);
        const key = pairKey(m.home, m.away);
        if (seenPairings.has(key)) errors.push(`${where}: duplicate pairing ${key} in this file`);
        seenPairings.add(key);
      } else {
        // locked — a teaser slot for a not-yet-playable team
        if (m.home !== null || m.away !== null) {
          errors.push(`${where}: locked match needs home/away = null (got ${JSON.stringify([m.home, m.away])})`);
        }
        if (!m.homeUpcoming || !m.awayUpcoming) {
          errors.push(`${where}: locked match needs homeUpcoming/awayUpcoming`);
        } else {
          for (const id of [m.homeUpcoming, m.awayUpcoming]) {
            if (!UPCOMING_TEAM_SET.has(id)) {
              warnings.push(`${where}: unknown upcoming team ${JSON.stringify(id)} — add it to UPCOMING_TEAM_SET or fix the id`);
            }
          }
        }
        if (m.when !== "—") errors.push(`${where}: locked match when must be "—" (got ${JSON.stringify(m.when)})`);
        if (m.score !== undefined) errors.push(`${where}: locked match must not carry a score`);
      }
    });
  });
  return { errors, warnings };
}

// ---- CLI --------------------------------------------------------------------

function parseArgs(argv) {
  const flags = { check: false, reset: false, rounds: null, currentRound: null };
  for (let i = 0; i < argv.length; i++) {
    switch (argv[i]) {
      case "--check":
        flags.check = true;
        break;
      case "--reset":
        flags.reset = true;
        break;
      case "--rounds":
        flags.rounds = Number(argv[++i]);
        break;
      case "--current-round":
        flags.currentRound = Number(argv[++i]);
        break;
      case "--help":
      case "-h":
        console.log(`sync-fixtures — generate / validate app/data/fixtures.json

Usage:
  node script/sync-fixtures.mjs               validate + extend + write back
  node script/sync-fixtures.mjs --check       validate only (exit 1 on error)
  node script/sync-fixtures.mjs --reset       rebuild 7 clean round-robin rounds
  node script/sync-fixtures.mjs --rounds N    target total round count (extend mode)
  node script/sync-fixtures.mjs --current-round N   which round is "today"

Extend mode keeps finished scores and announced kick-offs verbatim, then
appends the remaining 8-team round-robin pairings as new rounds.`);
        process.exit(0);
        break;
      default:
        console.error(`sync-fixtures: unknown flag ${argv[i]}`);
        process.exit(2);
    }
  }
  return flags;
}

function printSummary(result, flags, stats) {
  const { errors, warnings } = validateFixtures(result);
  const newRounds = stats.newRounds;
  const keptRounds = result.rounds.length - newRounds.length;
  if (flags.check) {
    console.log(
      `[fixtures] check ok — ${keptRounds} round${keptRounds === 1 ? "" : "s"} valid, would add ${newRounds.length} round${newRounds.length === 1 ? "" : "s"} (${stats.newMatches} matches)`,
    );
  } else {
    console.log(
      `[fixtures] sync ok — ${keptRounds} kept, ${newRounds.length} new round${newRounds.length === 1 ? "" : "s"} (${result.rounds.length} total)`,
    );
    if (stats.newMatches > 0) {
      const ids = newRounds.map((r) => r.id).join(" ");
      console.log(`[fixtures] added ${stats.newMatches} matches: ${ids}`);
    }
  }
  for (const w of warnings) console.warn(`[fixtures] warning: ${w}`);
  if (errors.length) {
    for (const e of errors) console.error(`[fixtures] error: ${e}`);
    process.exit(1);
  }
}

function main() {
  const flags = parseArgs(process.argv.slice(2));

  let existing = null;
  if (existsSync(FIXTURES_PATH)) {
    try {
      existing = JSON.parse(readFileSync(FIXTURES_PATH, "utf8"));
    } catch (err) {
      console.error(`[fixtures] cannot parse ${FIXTURES_PATH}: ${err.message}`);
      process.exit(1);
    }
  } else if (flags.check) {
    console.error(`[fixtures] ${FIXTURES_PATH} does not exist — nothing to check`);
    process.exit(1);
  }

  // validate the current file first, whatever mode we run in
  if (existing) {
    const { errors, warnings } = validateFixtures(existing);
    for (const w of warnings) console.warn(`[fixtures] warning: ${w}`);
    if (errors.length) {
      for (const e of errors) console.error(`[fixtures] error: ${e}`);
      console.error(`[fixtures] existing file is invalid — fix it or regenerate with --reset`);
      process.exit(1);
    }
  }

  let result;
  let stats;
  if (flags.reset) {
    const rounds = buildResetRounds();
    result = {
      updatedAt: new Date().toISOString().slice(0, 10),
      source: SOURCE_LINE,
      currentRound: flags.currentRound ?? 1,
      rounds,
    };
    stats = { newRounds: rounds, newMatches: rounds.reduce((n, r) => n + r.matches.length, 0) };
  } else {
    const base = existing ?? { updatedAt: "", source: SOURCE_LINE, currentRound: flags.currentRound ?? 1, rounds: [] };
    const existingRounds = base.rounds.length;
    const used = countUsedPairings(base);
    // Default: schedule every remaining pairing. There is no safe ceil()
    // guess here — a greedy round may take fewer than 4 matches when the
    // committed history blocks the pairing graph, so we simply run until
    // `fresh` is empty (or the caller's --rounds cap, if any).
    const targetRounds = flags.rounds ?? Infinity;
    if (flags.rounds && targetRounds < existingRounds) {
      console.error(`[fixtures] --rounds ${flags.rounds} is below the existing ${existingRounds} rounds`);
      process.exit(2);
    }
    const newRounds = buildExtendedRounds(base, targetRounds);
    result = {
      updatedAt: new Date().toISOString().slice(0, 10),
      source: SOURCE_LINE,
      currentRound: base.currentRound,
      rounds: [...base.rounds, ...newRounds],
    };
    stats = { newRounds, newMatches: newRounds.reduce((n, r) => n + r.matches.length, 0) };
  }

  printSummary(result, flags, stats);

  if (flags.check) return; // read-only

  writeFileSync(FIXTURES_PATH, JSON.stringify(result, null, 2) + "\n");
  console.log(`[fixtures] wrote ${FIXTURES_PATH}`);
}

// Run only when executed directly — importing this module (e.g. from a test)
// must not rewrite the fixtures file.
if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  main();
}
